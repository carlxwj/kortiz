  function translate(text, forceLang = language()) {
    if (forceLang === 'fr' || !text) return String(text ?? '');
    const raw = String(text), trimmed = raw.trim();
    if (!trimmed) return raw;
    const translated = DICT[trimmed]?.[forceLang] || interpolate(trimmed,forceLang);
    if (translated === trimmed) return raw;
    return raw.slice(0,raw.indexOf(trimmed)) + translated + raw.slice(raw.indexOf(trimmed)+trimmed.length);
  }
  function nodeTranslate(n) {
    if(n.nodeType === Node.TEXT_NODE){
      if(n.parentElement?.closest('script,style,textarea,option[data-no-translate],[contenteditable],.no-translate'))return;
      const state=orig.get(n);
      const original=state && n.nodeValue === state.output ? state.original : n.nodeValue;
      const output=translate(original);
      orig.set(n,{original,output});
      if(n.nodeValue!==output)n.nodeValue=output;
    }else if(n.nodeType === Node.ELEMENT_NODE){
      // Ne pas modifier le contenu saisi dans un textarea, mais traduire
      // ses attributs (placeholder/aria-label/title) comme ceux des inputs.
      if(n.matches('script,style,.no-translate'))return;
      const saved=attrOrig.get(n)||{};
      for (const attr of ['placeholder','aria-label','title','alt']) {
        if(!n.hasAttribute(attr))continue;
        const current=n.getAttribute(attr);
        const prior=saved[attr];
        // Keep the original French source only while the visible value still
        // matches our own translation; respect new attributes inserted by code.
        const original=prior && current===prior.output ? prior.original : current;
        const result=translate(original);
        saved[attr]={original,output:result};
        if(current!==result)n.setAttribute(attr,result);
      }
      attrOrig.set(n,saved);
      if(n.matches('textarea,[contenteditable]'))return;
      for(const child of n.childNodes)nodeTranslate(child);
    }
  }
